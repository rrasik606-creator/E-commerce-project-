import mongoose from "mongoose";

const productSchema = new mongoose.Schema(
    {
        name:{
            type:String,
            required:true,
            trim:true
        },
        brand:{
            type:String,
            required:true,
            trim:true
        },
        category:{
            type:String,
            required:true,
            enum:["men","women"]
        }, 
        type:{
            type:String,
            required:true,
            trim:true,
            lowercase:true
        },
        price:{
            type:Number,
            required:true,
            min:0
        },
        originalPrice:{
            type:Number,
            required:true,
            min:0
        },
        discount:{
            type:Number,
            default:0,
            min:0,
            max:100
        },
        rating:{
            type:Number,
            default:0,
            min:0,
            max:5
        },
        reviews:{
            type:Number,
            default:0,
            min:0
        },
        image:{
            type:[String],
            required:true
        },
        description:{
            type:String,
            required:true,
        },
        features:{
            type:[String],
            default:[]
        },
        stock:{
            type:Number,
            required:true,
            default:0,
            min:0
        },
        featured:{
            type:Boolean,
            default:false
        },
        isNew:{
            type:Boolean,
            default:false
        },
        deleted:{
            type:Boolean,
            default:false
        }
    },
    {timestamps:true}
);

const Product=mongoose.model("Product",productSchema)

export default Product